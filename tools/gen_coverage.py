#!/usr/bin/env python3
"""Generate COVERAGE.md: public kernel32/kernelbase surface vs. names referenced by tests/.
A name counts as referenced when it appears as U/UK/UB/UNT/UN/U_/NTP(Name) or t_proc*("Name")
anywhere in tests/ (macro definitions included, REQUIRE-only mentions excluded)."""
import re, os, collections
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda f: [l.strip() for l in open(os.path.join(root, 'tools', f)) if l.strip()]
pub = set(rd('public_surface.txt')); k32 = set(rd('kernel32_exports.txt')); kb = set(rd('kernelbase_exports.txt'))
hdr = dict(l.split('\t') for l in rd('public_surface_by_header.txt') if '\t' in l)
pat = re.compile(r'\b(?:UK|UB|UNT|UN|U_|U|NTP)\(\s*([A-Za-z_]\w*)\s*\)|\bt_proc\w*\(\s*"([A-Za-z_]\w*)"\s*\)|"([A-Za-z_]\w+)"')
req = re.compile(r'REQUIRE\s*\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)')
uses = collections.Counter(); calls = collections.Counter(); areas = collections.defaultdict(set)
for d, _, fs in os.walk(os.path.join(root, 'tests')):
    for f in fs:
        if not f.endswith(('.c', '.h')): continue
        area = os.path.basename(d)
        for ln in open(os.path.join(d, f), errors='replace'):
            s = req.sub('', ln)
            for m in pat.finditer(s):
                n = m.group(1) or m.group(2) or m.group(3)
                if n in pub or n in k32 or n in kb:
                    if m.group(1) or m.group(2): calls[n] += 1
                    # bare string literals only count when they are an exact export name
                    uses[n] += 1; areas[n].add(area)
reasons = [
 (re.compile(r'^(SetSystemTime|SetLocalTime|SetTimeZoneInformation|SetDynamicTimeZoneInformation|SetSystemTimeAdjustment\w*|SetComputerName\w*|SetVolumeLabel\w*|SetSystemFileCacheSize|ExitWindowsEx|FatalAppExit\w*|Beep|SetSystemPowerState|SetSuspendState)$'),
  'state-changing for the whole machine: only argument-validation failure paths (verified from reference analysis) or presence are tested'),
 (re.compile(r'^(DefineDosDevice\w*|SetVolumeMountPoint\w*|DeleteVolumeMountPoint\w*)$'), 'only provably failing / self-cleaning unique-name paths'),
 (re.compile(r'^Wer'), 'WER registration touches per-process crash-report state; presence and error paths only'),
]
def why(n):
    for r, t in reasons:
        if r.match(n): return t
    return 'no direct call found by static scan (may be exercised through helper tables); see tests/gap_* presence checks'
out = []
a = out.append
cov = sorted(n for n in pub if uses[n]); unc = sorted(n for n in pub if not uses[n])
called = sorted(n for n in pub if calls[n]); notcalled = sorted(n for n in pub if not calls[n] and uses[n])
a('# Coverage\n')
a(f'Public Win32 surface exported by kernel32/kernelbase (tools/public_surface.txt): **{len(pub)}** names; referenced by tests: **{len(cov)}** ({100*len(cov)/len(pub):.1f}%); not referenced at all: {len(unc)}. Resolved through U()/UK()/UB()/t_proc (call or presence/forwarder check): **{len(called)}** ({100*len(called)/len(pub):.1f}%); names that only occur as quoted strings in export tables / presence lists: {len(notcalled)}.\n')
a('Generated by `python3 tools/gen_coverage.py > COVERAGE.md`. "Referenced" is a static scan of `tests/` for `U()/UK()/UB()/UNT()/UN()` and `t_proc*("Name")` uses, so it is an upper bound on dynamic behaviour covered; `tools/coverage.py` gives the stricter count of call sites.\n')
a('## Module split\n')
only_k = pub & k32 - kb; only_b = pub & kb - k32; both = pub & k32 & kb
a('| set | public names | referenced |'); a('|---|---|---|')
for lab, s in (('kernel32 only', only_k), ('kernelbase only', only_b), ('both (kernel32 forwards or duplicates)', both), ('neither (header-only / other DLL)', pub - k32 - kb)):
    a(f'| {lab} | {len(s)} | {sum(1 for n in s if uses[n])} |')
a('\nOne corpus covers both DLLs: tests resolve each name with `U()` (kernel32 first, then kernelbase), and `UK()`/`UB()` pin the exporting module where forwarder behaviour matters. Separate repos would duplicate all scaffolding and split the many kernel32-to-kernelbase forwarder checks, hence a single repo (kernel32_kernelbase).\n')
a('## Per header\n'); a('| header | public | referenced |'); a('|---|---|---|')
byh = collections.defaultdict(list)
for n in pub: byh[hdr.get(n, '?')].append(n)
for h in sorted(byh): a(f'| {h} | {len(byh[h])} | {sum(1 for n in byh[h] if uses[n])} |')
a('\n## Public names without a U()/UK()/UB()/t_proc lookup\n'); a('| name | header | reason |'); a('|---|---|---|')
for n in sorted(set(unc) | set(notcalled)): a(f'| {n} | {hdr.get(n, "?")} | {why(n)} |')
a('\n## Exports outside the public surface (internal/undocumented)\n')
oth = sorted((k32 | kb) - pub)
oc = [n for n in oth if uses[n]]
a(f'{len(oth)} names; referenced {len(oc)}; presence/safe-behaviour tests live in gap_20..gap_29 and gap_24. Unreferenced: {len(oth)-len(oc)} (mostly ordinal-only helpers, internal Base*/Basep* routines, CRT-style stubs whose signatures are not documented).\n')
a('## Deliberately never invoked (safety)\n')
a('Called only on error paths proven to fail before any side effect, or in a disposable child process: SetSystemTime, SetLocalTime, SetTimeZoneInformation, SetDynamicTimeZoneInformation, SetComputerName*, SetVolumeLabel, DefineDosDevice (unique K32T names only), SetVolumeMountPoint, DeleteVolumeMountPoint, SetSystemTimeAdjustment, SetSystemFileCacheSize, SetProcessDEPPolicy (child only), FatalAppExit*, FatalExit, ExitWindowsEx, Beep/MessageBeep, SetSystemPowerState, console control (GenerateConsoleCtrlEvent, FreeConsole, AttachConsole, AllocConsole: child with its own or no console only), debugging (only processes the test created).\n')
print('\n'.join(out))
