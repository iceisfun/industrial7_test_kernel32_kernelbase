#!/bin/sh
# Regenerates ../modblob.h (committed). Requires mingw-w64 + xxd.
set -e
cd "$(dirname "$0")"
CC=x86_64-w64-mingw32-gcc
P=x86_64-w64-mingw32
LF="-nostdlib -shared -Wl,-e,DllMain -Wl,--file-alignment,512 -Wl,--section-alignment,4096 -Wl,--dynamicbase -Wl,--nxcompat -s"
$P-windres moda.rc -o moda_rc.o
$CC -O1 -c moda.c -o moda.o
$CC $LF -Wl,--image-base,0x1D0000000 -o k32m_a.dll moda.o moda_rc.o moda.def
$CC -O1 -c modd.c -o modd.o
$CC $LF -Wl,--image-base,0x1D1000000 -o k32m_dep.dll modd.o modd.def
$P-dlltool -d modd.def -l libk32m_dep.a -D k32m_dep.dll
$CC -O1 -c modi.c -o modi.o
$CC $LF -Wl,--image-base,0x1D2000000 -o k32m_imp.dll modi.o libk32m_dep.a modi.def
$CC -O1 -c modf.c -o modf.o
$CC $LF -Wl,--image-base,0x1D3000000 -o k32m_fail.dll modf.o modf.def
$P-dlltool -d fakedep.def -l libfakedep.a -D k32m_dep.dll
$CC -O1 -c modb.c -o modb.o
$CC $LF -Wl,--image-base,0x1D4000000 -o k32m_badimp.dll modb.o libfakedep.a modb.def
out=../modblob.h
echo "/* generated by gen/gen.sh - test DLL images */" > $out
for n in k32m_a k32m_dep k32m_imp k32m_fail k32m_badimp; do
  echo "static const unsigned char blob_$n[] = {" >> $out
  xxd -i < $n.dll >> $out
  echo "};" >> $out
done
rm -f *.o *.a *.dll
